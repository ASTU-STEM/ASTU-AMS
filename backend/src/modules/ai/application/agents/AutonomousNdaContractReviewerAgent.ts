import { AutonomousNotificationDispatcher } from '../services/AutonomousNotificationDispatcher';

export interface NdaReviewResult {
  contractTitle: string;
  flaggedRiskyClauses: string[];
  recommendedModifications: string[];
  auditDispatched: boolean;
}

export class AutonomousNdaContractReviewerAgent {
  /**
   * Reads partnership agreement (MoU/NDA) contract drafts with employers, highlights risky clauses,
   * and recommends modifications aligned with ASTU legal guidelines.
   */
  public static async reviewContractDraft(contractText = 'ASTU-Safaricom Master Industry MoU Draft'): Promise<NdaReviewResult> {
    const contractTitle = 'ASTU-Employer Strategic Partnership MoU & Non-Disclosure Agreement (NDA)';
    
    const flaggedRiskyClauses = [
      'Clause 4.2: Exclusivity constraint preventing ASTU from partnering with competing telecom providers for 3 years.',
      'Clause 8.1: Overly broad IP assignment transferring all student capstone innovations to host employer.',
    ];

    const recommendedModifications = [
      'Modify Clause 4.2: Replace non-compete exclusivity with non-exclusive collaborative research status.',
      'Modify Clause 8.1: Specify co-ownership of patent rights between ASTU and host employer for capstone projects.',
    ];

    const reviewReportContent = `ADAMA SCIENCE & TECHNOLOGY UNIVERSITY (ASTU)
LEGAL COUNSEL OFFICE & CONTRACT AUDIT ENGINE

LEGAL REVIEW & CONTRACT AUDIT REPORT
CONTRACT: ${contractTitle}

1. FLAGGED RISKY CLAUSES:
${flaggedRiskyClauses.map((c, i) => `${i + 1}. ${c}`).join('\n')}

2. RECOMMENDED LEGAL MODIFICATIONS:
${recommendedModifications.map((m, i) => `${i + 1}. ${m}`).join('\n')}

Review report generated by ASTU Autonomous NDA & Contract Reviewer Agent for Legal Office approval.`;

    let auditDispatched = false;
    try {
      await AutonomousNotificationDispatcher.dispatchProposalNotification({
        title: `LEGAL CONTRACT AUDIT: ${contractTitle}`,
        documentSubject: `ASTU_Legal_Contract_Audit_Report`,
        documentFormat: 'PDF',
        documentContent: reviewReportContent,
        targetRoles: ['VPAA', 'DEAN', 'REGISTRAR', 'SUPER_ADMIN'],
      }).then(() => { auditDispatched = true; }).catch(() => {});
    } catch {}

    return {
      contractTitle,
      flaggedRiskyClauses,
      recommendedModifications,
      auditDispatched,
    };
  }
}
